// Generates everything search engines and AI crawlers read, from the LABS array in index.html:
//   sitemap.xml, llms.txt, and the <noscript> lab list inside index.html (the cards themselves are drawn by script).
// Pages marked noindex and the secret lab are left out. Runs from the pre-commit hook (tools/hooks/pre-commit).
// Usage: node tools/sync-seo.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ORIGIN = 'https://labs.chuckwired.com';
const root = new URL('../', import.meta.url);
const p = f => fileURLToPath(new URL(f, root));
const html = readFileSync(p('index.html'), 'utf8');

const a = html.indexOf('var LABS = ['), b = html.indexOf('];', a) + 1;
const LABS = new Function(html.slice(a, b).replace('var LABS =', 'return') + ';')();
const indexable = f => existsSync(p(f)) && !/noindex/.test(readFileSync(p(f), 'utf8'));
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

const labs = LABS.filter(l => !l.secret && indexable(l.path + 'index.html'));
const extra = [['performance/', null], ['made-to-be-played/direction/', '2026-10-26']].filter(([u]) => indexable(u + 'index.html')); // site pages that are not labs (the index hero's write-up has no lab of its own)

// sitemap.xml
const urls = [['', labs.map(l => l.date).sort().pop()], ...labs.flatMap(l => [[l.path, l.date], ...(l.notes && indexable(l.notes + 'index.html') ? [[l.notes, l.date]] : [])]), ...extra];
writeFileSync(p('sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(([u, d]) => `  <url><loc>${ORIGIN}/${u}</loc>${d ? `<lastmod>${d}</lastmod>` : ''}</url>`).join('\n')}\n</urlset>\n`);

// llms.txt: a plain-text map for language-model crawlers (llmstxt.org format)
writeFileSync(p('llms.txt'), `# Chuck Rice Labs

> Interactive experiments by Chuck Rice, a product designer who ships production code. Each lab is a small, dependency-free web page; every one has a "Behind the design" write-up explaining the choices. Source: https://github.com/chuckwired/labs

## Labs
${labs.map(l => `- [${l.title}](${ORIGIN}/${l.path}): ${l.blurb.replace(/\s+/g, ' ')}`).join('\n')}

## Behind the design
${[...labs.filter(l => l.notes && indexable(l.notes + 'index.html')).map(l => `- [${l.title}: behind the design](${ORIGIN}/${l.notes})`), ...extra.filter(([u]) => u.endsWith('/direction/')).map(([u]) => `- [Made to be played (the hero): behind the design](${ORIGIN}/${u})`)].join('\n')}

## About the site
- [Performance](${ORIGIN}/performance/): how the site is built, what each page weighs, and how it handles performance, accessibility and search.
- [Portfolio](https://chuckwired.com) and [writing](https://chuckwired.medium.com) by the same author.
`);

// crawlable list for anything that does not run the page's script
const list = labs.map(l => `    <li><a href="${l.path}">${esc(l.title)}</a>: ${esc(l.blurb.replace(/\s+/g, ' '))}${l.notes && indexable(l.notes + 'index.html') ? ` <a href="${l.notes}">Behind the design</a>` : ''}</li>`).join('\n');
const block = `<!--labs:start (generated by tools/sync-seo.mjs)-->\n<noscript>\n  <ul>\n${list}\n  </ul>\n</noscript>\n<!--labs:end-->`;
const out = html.replace(/<!--labs:start[\s\S]*?<!--labs:end-->/, block);
if (out === html && !html.includes('<!--labs:start')) throw new Error('markers <!--labs:start--> / <!--labs:end--> missing in index.html');
if (out !== html) writeFileSync(p('index.html'), out);
console.log(`synced seo: ${urls.length} urls, ${labs.length} labs`);
